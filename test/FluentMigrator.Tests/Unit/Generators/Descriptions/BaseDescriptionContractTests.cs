using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

using FluentMigrator.Exceptions;
using FluentMigrator.Runner;
using FluentMigrator.Tests.SyntaxRoots;

using NUnit.Framework;

using VerifyNUnit;

namespace FluentMigrator.Tests.Unit.Generators.Descriptions
{
    /// <summary>
    /// The contract every generator keeps for table and column descriptions, for every fluent syntax root that sets
    /// one (issue #2351). Needs no database.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Each scenario is a migration written with one syntax root (<see cref="DescriptionScenario"/>). It runs through
    /// the runner without a connection, so the SQL comes from the same builders, conventions, processor and generator
    /// that write a migration script. A generator's own unit tests build expressions by hand and so skip the builders,
    /// which is how PostgreSQL and Snowflake came to drop descriptions without a failing test.
    /// </para>
    /// <para>
    /// A subclass says how to configure the runner and, for any root it doesn't support, that the SQL has no
    /// description (<see cref="Support"/>). Two checks follow:
    /// </para>
    /// <list type="bullet">
    /// <item><see cref="TheSqlSetsEveryDescription"/>: the SQL has every description text, or none where the subclass
    /// says the root isn't supported, so a gap is declared rather than silent, and closing it is a deliberate change.</item>
    /// <item><see cref="TheSqlOfEveryRootIsStable"/>: the exact SQL, as a snapshot next to this file, one per database.
    /// A change to a generator shows up as a diff of the statements it changes.</item>
    /// </list>
    /// <para>
    /// The processor integration tests (<c>BaseDescriptionTests</c>) run the same scenarios on real databases and read the
    /// descriptions back from the catalog.
    /// </para>
    /// </remarks>
    [Category("Generator")]
    [Category("Description")]
    public abstract class BaseDescriptionContractTests
    {
        /// <summary>
        /// Adds the database to the runner, for example <c>builder.AddPostgres()</c>.
        /// </summary>
        protected abstract void ConfigureRunner(IMigrationRunnerBuilder builder);

        /// <summary>
        /// What the generator does with the descriptions of <paramref name="root"/>. All are written unless a subclass
        /// says otherwise.
        /// </summary>
        protected virtual DescriptionSupport Support(DescriptionRoot root) => DescriptionSupport.Written;

        public static IEnumerable<DescriptionScenario> Scenarios => DescriptionScenario.All;

        [TestCaseSource(nameof(Scenarios))]
        public void TheSqlSetsEveryDescription(DescriptionScenario scenario)
        {
            if (Support(scenario.Root) == DescriptionSupport.RootNotSupported)
            {
                Assert.Throws<DatabaseOperationNotSupportedException>(() => Generate(scenario));
                return;
            }

            var sql = string.Join(Environment.NewLine, Generate(scenario));

            Assert.Multiple(
                () =>
                {
                    foreach (var text in scenario.ExpectedTexts)
                    {
                        if (Support(scenario.Root) == DescriptionSupport.Written)
                        {
                            Assert.That(sql, Does.Contain(text), $"{scenario.Syntax} should set \"{text}\"");
                        }
                        else
                        {
                            Assert.That(sql, Does.Not.Contain(text), $"{scenario.Syntax} is declared NotWritten but sets \"{text}\"");
                        }
                    }
                });
        }

        [Test]
        public Task TheSqlOfEveryRootIsStable()
        {
            var markdown = new StringBuilder();
            markdown.AppendLine($"# Descriptions: the SQL of every syntax root ({GetType().Name})");
            markdown.AppendLine();
            markdown.AppendLine("Generated by `BaseDescriptionContractTests`. Each section is one migration; its SQL is what a connectionless script would contain.");

            foreach (var scenario in DescriptionScenario.All)
            {
                markdown.AppendLine();
                markdown.AppendLine($"## {scenario.Root}: `{scenario.Syntax}`");
                markdown.AppendLine();
                markdown.AppendLine($"Descriptions: {Support(scenario.Root)}");
                markdown.AppendLine();
                markdown.AppendLine("```sql");
                try
                {
                    foreach (var statement in Generate(scenario))
                    {
                        markdown.AppendLine(statement.Replace("\r\n", "\n").TrimEnd());
                    }
                }
                catch (DatabaseOperationNotSupportedException ex) when (Support(scenario.Root) == DescriptionSupport.RootNotSupported)
                {
                    markdown.AppendLine($"-- {nameof(DatabaseOperationNotSupportedException)}: {ex.Message}");
                }

                markdown.AppendLine("```");
            }

            return Verifier.Verify(markdown.ToString(), "md");
        }

        private IReadOnlyList<string> Generate(DescriptionScenario scenario) =>
            SyntaxRootRunner.Script(
                ConfigureRunner,
                scenario.NeedsExistingTable ? scenario.Arrange() : null,
                scenario.Act())
            .Where(statement => !string.IsNullOrWhiteSpace(statement))
            .ToList();
    }
}
